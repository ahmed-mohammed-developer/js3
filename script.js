
/* =========================================================
   1. تحديد عناصر HTML التي سنتعامل معها
   ========================================================= */

// نبحث عن العنصر الذي يحتوي على معرض الصور باستخدام data-gallery
const gallery = document.querySelector("[data-gallery]");

// نحصل على جميع أزرار الصور المصغّرة الموجودة داخل المعرض
// Array.from يحوّل NodeList إلى مصفوفة JavaScript
// حتى نستطيع استخدام دوال المصفوفات مثل forEach
const galleryItems = Array.from(
  gallery.querySelectorAll(".gallery__item")
);

// نصل إلى نافذة عرض الصور المكبّرة التي تحمل الخاصية data-lightbox
const lightbox = document.querySelector("[data-lightbox]");

// نصل إلى عنصر الصورة الكبيرة التي سيتغير مصدرها عند التنقل
const largeImage = lightbox.querySelector("[data-lightbox-image]");

// نصل إلى العنصر الذي سيعرض وصف الصورة الحالية
const caption = lightbox.querySelector("[data-lightbox-caption]");

// نصل إلى العنصر الذي سيعرض رقم الصورة الحالية، مثل 2 من 6
const counter = lightbox.querySelector("[data-counter]");

// نحدد زر إغلاق النافذة
const closeButton = lightbox.querySelector("[data-close]");

// نحدد زر الانتقال إلى الصورة السابقة
const previousButton = lightbox.querySelector("[data-previous]");

// نحدد زر الانتقال إلى الصورة التالية
const nextButton = lightbox.querySelector("[data-next]");


/* =========================================================
   2. إنشاء المتغيرات التي تحفظ حالة المعرض
   ========================================================= */

// يخزن فهرس الصورة الحالية داخل المصفوفة
// تبدأ الفهارس من الصفر؛ لذلك فهرس أول صورة هو 0
let currentIndex = 0;

// يخزن العنصر الذي كان المستخدم يركز عليه قبل فتح النافذة
// نحتاج إليه لإعادة التركيز إلى الصورة نفسها بعد إغلاق النافذة
let lastFocusedItem = null;


/* =========================================================
   3. دالة عرض الصورة وتحديث بياناتها
   ========================================================= */

// تستقبل الدالة رقم فهرس الصورة التي نريد عرضها
function showImage(index) {

  // نحسب فهرسًا صالحًا يسمح بالتنقل الدائري بين الصور:
  // إذا تجاوزنا آخر صورة نعود إلى الأولى
  // وإذا رجعنا قبل الصورة الأولى ننتقل إلى الأخيرة
  currentIndex =
    (index + galleryItems.length) % galleryItems.length;

  // نحصل على زر الصورة المصغّرة الموجودة في الفهرس الحالي
  const selectedItem = galleryItems[currentIndex];

  // نصل إلى عنصر img الموجود داخل زر الصورة المصغّرة
  // حتى نستفيد من النص البديل المكتوب في خاصية alt
  const thumbnail = selectedItem.querySelector("img");

  // نضع رابط الصورة عالية الجودة في الصورة الكبيرة
  // dataset.full يقرأ قيمة الخاصية data-full من HTML
  largeImage.src = selectedItem.dataset.full;

  // ننقل النص البديل من الصورة المصغّرة إلى الصورة الكبيرة
  // لمساعدة مستخدمي قارئات الشاشة على فهم محتوى الصورة
  largeImage.alt = thumbnail.alt;

  // نعرض وصف الصورة من الخاصية data-caption
  // نستخدم textContent لإدراج النص بأمان دون تفسيره كـ HTML
  caption.textContent = selectedItem.dataset.caption;

  // نحدّث عداد الصور:
  // currentIndex + 1 لأن الفهرسة تبدأ من صفر
  // galleryItems.length يمثل العدد الإجمالي للصور
  // مثال: 2 من 6
  counter.textContent =
    `${currentIndex + 1} من ${galleryItems.length}`;
}


/* =========================================================
   4. فتح نافذة الصورة عند الضغط على صورة مصغّرة
   ========================================================= */

// نمر على جميع الصور المصغّرة داخل المعرض
// item يمثل عنصر الصورة الحالي، وindex يمثل فهرسه
galleryItems.forEach((item, index) => {

  // نضيف حدث click لكل صورة
  // ينفذ هذا الكود عندما يضغط المستخدم على الصورة
  item.addEventListener("click", () => {

    // نحفظ الصورة التي ضغط عليها المستخدم
    // حتى نعيد التركيز إليها عند إغلاق النافذة
    lastFocusedItem = item;

    // نعرض الصورة التي ضغط عليها المستخدم
    showImage(index);

    // نفتح عنصر dialog كنافذة حوار مشروطة
    // تظهر النافذة فوق الصفحة وتمنع التفاعل مع بقية الصفحة
    lightbox.showModal();

    // نضيف الصنف is-locked إلى body
    // ويستخدمه CSS لمنع تمرير الصفحة أثناء فتح النافذة
    document.body.classList.add("is-locked");

    // ننقل التركيز إلى زر الإغلاق
    // حتى يستطيع مستخدم لوحة المفاتيح إغلاق النافذة بسهولة
    closeButton.focus();
  });
});


/* =========================================================
   5. إغلاق النافذة باستخدام زر الإغلاق
   ========================================================= */

// نراقب الضغط على زر الإغلاق الموجود داخل النافذة
closeButton.addEventListener("click", () => {

  // close تغلق نافذة dialog
  // وسيُنفذ حدث close المسجل لاحقًا عند إغلاقها
  lightbox.close();
});


/* =========================================================
   6. الانتقال إلى الصورة السابقة
   ========================================================= */

// عند الضغط على زر السابق، نستدعي دالة عرض الصورة
previousButton.addEventListener("click", () => {

  // نطرح واحدًا من الفهرس الحالي
  // تتولى showImage معالجة الانتقال من الأولى إلى الأخيرة
  showImage(currentIndex - 1);
});


/* =========================================================
   7. الانتقال إلى الصورة التالية
   ========================================================= */

// عند الضغط على زر التالي، نستدعي دالة عرض الصورة
nextButton.addEventListener("click", () => {

  // نضيف واحدًا إلى الفهرس الحالي
  // تتولى showImage العودة إلى الصورة الأولى بعد الأخيرة
  showImage(currentIndex + 1);
});


/* =========================================================
   8. إغلاق النافذة عند الضغط على الخلفية الداكنة
   ========================================================= */

// نراقب النقرات داخل عنصر dialog
lightbox.addEventListener("click", (event) => {

  // event.target هو العنصر الذي استقبل النقر مباشرة
  // إذا كان هو dialog نفسه، فهذا يعني أن النقر كان على
  // الخلفية خارج المحتوى الداخلي للنافذة
  if (event.target === lightbox) {

    // نغلق النافذة
    lightbox.close();
  }
});


/* =========================================================
   9. التنقل بين الصور باستخدام لوحة المفاتيح
   ========================================================= */

// نستمع إلى أحداث لوحة المفاتيح عندما تكون النافذة مفتوحة
lightbox.addEventListener("keydown", (event) => {

  // إذا ضغط المستخدم على السهم الأيمن
  if (event.key === "ArrowRight") {

    // نمنع المتصفح من تنفيذ السلوك الافتراضي لهذا المفتاح
    event.preventDefault();

    // نعرض الصورة التالية
    showImage(currentIndex + 1);
  }

  // إذا ضغط المستخدم على السهم الأيسر
  if (event.key === "ArrowLeft") {

    // نمنع السلوك الافتراضي للمفتاح
    event.preventDefault();

    // نعرض الصورة السابقة
    showImage(currentIndex - 1);
  }

  // لا نحتاج إلى كتابة شرط لمفتاح Escape هنا
  // لأن عنصر dialog يغلق نفسه تلقائيًا عند ضغط Escape
  // ما لم يمنع كود آخر هذا السلوك
});


/* =========================================================
   10. تنظيف الحالة بعد إغلاق النافذة
   ========================================================= */

// يستمع هذا الحدث إلى إغلاق dialog
// سواء أُغلقت بزر الإغلاق أو بمفتاح Escape
lightbox.addEventListener("close", () => {

  // نحذف الصنف الذي يمنع تمرير الصفحة
  // حتى يتمكن المستخدم من التمرير بصورة طبيعية مجددًا
  document.body.classList.remove("is-locked");

  // نحذف خاصية src من الصورة الكبيرة
  // لتفريغ مصدر الصورة عند إغلاق النافذة
  largeImage.removeAttribute("src");

  // نتأكد من وجود العنصر السابق وأنه ما زال داخل الصفحة
  if (lastFocusedItem && lastFocusedItem.isConnected) {

    // نعيد التركيز إلى الصورة التي فتحت النافذة
    // وهذا يساعد مستخدمي لوحة المفاتيح على متابعة التصفح
    lastFocusedItem.focus();
  }

  // نفرغ المتغير بعد الانتهاء من استخدامه
  // حتى لا نحتفظ بمرجع غير ضروري إلى العنصر السابق
  lastFocusedItem = null;
});
